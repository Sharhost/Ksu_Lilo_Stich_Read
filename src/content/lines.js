const last = {}; // последняя реплика каждого события — чтобы не повторяться подряд
export function line(event) {
  const bank = BANK[event] || BANK.start;
  let i = Math.floor(Math.random() * bank.length);
  if (bank.length > 1 && i === last[event]) i = (i + 1) % bank.length;
  last[event] = i;
  return bank[i];
}
